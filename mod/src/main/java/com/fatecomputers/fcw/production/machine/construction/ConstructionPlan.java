package com.fatecomputers.fcw.production.machine.construction;

import com.fatecomputers.fcw.production.ProductionDifficulty;
import com.fatecomputers.fcw.production.machine.MachineDef;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.Item;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

/**
 * How a machine is built: its stages with their components and time
 * ({@code data/fcw/construction/<machine>.json}, generated by mod/tools/production/gen.py from the same
 * tables as the recipes and the docs), and which cells each stage raises. Read from the mod jar on both
 * sides. The numbers in the file are those of the difficulty "engineer"; {@link ProductionDifficulty}
 * scales them.
 */
public final class ConstructionPlan {
    /** @param count as written in the bill (engineer level) */
    public record Entry(ResourceLocation itemId, int count) {
        public Item item() {
            return BuiltInRegistries.ITEM.get(itemId);
        }

        /** How many are needed on the current difficulty. */
        public int need() {
            return ProductionDifficulty.current().scale(count);
        }
    }

    /**
     * @param firstCell index in {@link #cells} of the stage's first cell
     * @param cellCount how many cells the stage raises
     */
    public record Stage(String id, String ru, String en, int seconds, List<Entry> entries, int firstCell, int cellCount) {
        public String title(String lang) {
            return lang != null && lang.startsWith("ru") ? ru : en;
        }

        public int ticks() {
            return ProductionDifficulty.current().stageTicks(seconds);
        }
    }

    private static final Map<String, ConstructionPlan> PLANS = new ConcurrentHashMap<>();

    public final List<Stage> stages = new ArrayList<>();
    /** Every cell but the terminal (the pallet stands there until the end), bottom to top. */
    public final List<MachineDef.Cell> cells = new ArrayList<>();

    private ConstructionPlan(MachineDef def) {
        for (MachineDef.Cell c : def.cells) {
            if (c.x() != def.terminal.x() || c.y() != def.terminal.y() || c.z() != def.terminal.z()) {
                cells.add(c);
            }
        }
        cells.sort(Comparator.<MachineDef.Cell>comparingInt(MachineDef.Cell::y).thenComparingInt(MachineDef.Cell::z).thenComparingInt(MachineDef.Cell::x));
        JsonObject json = MachineDef.readJson("/data/fcw/construction/" + def.name + ".json");
        List<JsonObject> raw = new ArrayList<>();
        int totalSeconds = 0;
        for (JsonElement e : json.getAsJsonArray("stages")) {
            raw.add(e.getAsJsonObject());
            totalSeconds += e.getAsJsonObject().get("seconds").getAsInt();
        }
        // cells go to the stages by the share of the build time, layer by layer from the ground up
        int first = 0, seconds = 0;
        for (int i = 0; i < raw.size(); i++) {
            JsonObject s = raw.get(i);
            seconds += s.get("seconds").getAsInt();
            int end = i == raw.size() - 1 ? cells.size() : (int) Math.round((double) cells.size() * seconds / totalSeconds);
            List<Entry> entries = new ArrayList<>();
            for (JsonElement ie : s.getAsJsonArray("items")) {
                JsonObject it = ie.getAsJsonObject();
                entries.add(new Entry(ResourceLocation.parse(it.get("item").getAsString()), it.get("count").getAsInt()));
            }
            stages.add(new Stage(s.get("id").getAsString(), s.get("ru").getAsString(), s.get("en").getAsString(),
                    s.get("seconds").getAsInt(), List.copyOf(entries), first, end - first));
            first = end;
        }
    }

    public static ConstructionPlan of(MachineDef def) {
        return PLANS.computeIfAbsent(def.name, n -> new ConstructionPlan(def));
    }

    /** Components of all stages together, on the current difficulty. */
    public int totalNeed() {
        int n = 0;
        for (Stage s : stages) {
            for (Entry e : s.entries()) {
                n += e.need();
            }
        }
        return n;
    }

    public int totalTicks() {
        int n = 0;
        for (Stage s : stages) {
            n += s.ticks();
        }
        return n;
    }
}
