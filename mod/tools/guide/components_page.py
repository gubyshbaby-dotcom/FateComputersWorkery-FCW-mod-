#!/usr/bin/env python3
"""Writes the guide page "Machine Components" (production/components.md, both languages).

    python3 mod/tools/guide/components_page.py [repo root]

The page is built from the same data the game reads: data/fcw/construction/*.json (stages and
bills, generated by mod/tools/production/gen.py) and the item names of assets/fcw/lang. Run it
after gen.py whenever the bills or the list of components change, then run check.py.
"""
import json
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..', '..')
res = os.path.join(root, 'mod', 'src', 'main', 'resources')
MACHINES = ['arc_furnace', 'crystal_puller', 'wafering_cell', 'euv_scanner_mk2', 'chip_line']

VANILLA = {'minecraft:tinted_glass': ('Тонированное стекло', 'Tinted Glass'), 'minecraft:hopper': ('Воронка', 'Hopper')}

TEXT = {
    'ru': dict(
        dir='_ru_ru', title='Компоненты машин',
        intro='Из компонентов собирают машины на стройплощадке: [Постройка машин](construction.md). Ведомости ниже даны для уровня `engineer`; на уровне `standard` нужна четверть, с округлением вверх. Свою ведомость площадки показывает команда `bom` на поддоне.',
        bills='Ведомости', stage='Этап', time='Время', items='Компоненты', minutes='%s мин', total='Всего этапов: %s, время сборки: %s мин.',
        recipes='Рецепты компонентов',
        proto='Опытные чипы для первого литографа описаны на странице [Постройка машин](construction.md).',
        euv='Блоки литографа и их рецепты: [Блоки литографа](euv-blocks.md).'),
    'en': dict(
        dir='', title='Machine Components',
        intro='Machines are assembled from components on a build site: [Building Machines](construction.md). The bills below are for the `engineer` level; the `standard` level needs a quarter, rounded up. The `bom` command on the pallet shows the bill of a particular site.',
        bills='Bills', stage='Stage', time='Time', items='Components', minutes='%s min', total='Stages: %s, build time: %s min.',
        recipes='Component recipes',
        proto='The prototype chips for the first scanner are described on the page [Building Machines](construction.md).',
        euv='The building blocks of the scanner and their recipes: [Scanner blocks](euv-blocks.md).'),
}


def load(*path):
    with open(os.path.join(res, *path), encoding='utf-8') as f:
        return json.load(f)


components = [c['id'] for c in load('data', 'fcw', 'construction', 'components.json')['components']]
plans = {m: load('data', 'fcw', 'construction', m + '.json') for m in MACHINES}

for code, t in TEXT.items():
    lang = load('assets', 'fcw', 'lang', 'ru_ru.json' if code == 'ru' else 'en_us.json')

    def name(item):
        if item in VANILLA:
            return VANILLA[item][0 if code == 'ru' else 1]
        path = item.split(':')[-1]
        return lang.get('item.fcw.' + path) or lang.get('block.fcw.' + path) or item

    out = ['---', 'navigation:', '  title: "%s"' % t['title'], '  parent: production/index.md', '  position: 4', '  icon: fcw:electric_motor', 'item_ids:']
    out += ['  - fcw:' + c for c in components]
    out += ['---', '', '# ' + t['title'], '', t['intro'], '', '## ' + t['bills'], '']
    for m in MACHINES:
        stages = plans[m]['stages']
        out += ['### ' + lang['machine.fcw.' + m], '', '| %s | %s | %s |' % (t['stage'], t['time'], t['items']), '|---|---|---|']
        for s in stages:
            items = ', '.join('%s %s' % (name(i['item']), i['count']) for i in s['items'])
            minutes = s['seconds'] / 60
            out.append('| %s | %s | %s |' % (s[code], t['minutes'] % (('%g' % minutes).replace('.', ',' if code == 'ru' else '.')), items))
        total = sum(s['seconds'] for s in stages) / 60
        out += ['', t['total'] % (len(stages), ('%g' % total).replace('.', ',' if code == 'ru' else '.')), '']
    out += [t['euv'], '', '## ' + t['recipes'], '']
    out += ['<RecipeFor id="fcw:%s" />' % c for c in components if not c.startswith('proto_')]
    out += ['', t['proto'], '']
    path = os.path.join(res, 'assets', 'fcw', 'fcwguide', t['dir'], 'production', 'components.md')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))
    print('wrote', os.path.relpath(path, root))
